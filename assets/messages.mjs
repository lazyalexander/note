const columns = Object.keys(languages);
const bySource = new Map();
for (const row of messages) {
  bySource.set(row[0], row);
  bySource.set(row[1], row);
}

export function formatMessage(language, source, ...values) {
  const column = columns.indexOf(language?.split("-")[0]);
  const text = bySource.get(source)?.[Math.max(0, column)] ?? source;
  return text.replace(/\{(\d+)\}/g, (key, index) => values[index] ?? key);
}

export function t(source, ...values) {
  return formatMessage(globalThis.document?.documentElement?.lang, source, ...values);
}
